import { BadRequestException } from "../errors/badrequest.error";
import { DatasetRepo } from "../repositories/dataset.repository";
import { EvaluationConfigRepo } from "../repositories/evaluationConfig.repository";
import { Competition, Dataset, DatasetType } from "../types/competition.types";
import readline from "readline";
import fs from "fs";

export class DatasetService {
	private datasetRepo: DatasetRepo;
	private evaluationConfigRepo: EvaluationConfigRepo;

	constructor(datasetRepo: DatasetRepo, evaluationConfigRepo: EvaluationConfigRepo) {
		this.datasetRepo = datasetRepo;
		this.evaluationConfigRepo = evaluationConfigRepo;
	}

	async createDatabaseEntryForUploadedFile(
		competition: Competition,
		datasetType: DatasetType,
		fileName: string,
		filePath: string,
	): Promise<Dataset> {
		// check if Dataset with same competitionId and datasetType already exists
		if (datasetType !== DatasetType.VALIDATION) {
			// Allow multiple validation datasets
			const existingDatasets = await this.datasetRepo.getDatasetsForCompetitionAndType(competition.id, datasetType);
			if (existingDatasets.length > 0) {
				throw new BadRequestException(
					`Dataset of type ${datasetType} already exists for competition ID ${competition.id}`,
				);
			}
		}
		// check if the file exists
		if (!fs.existsSync(filePath)) {
			throw new Error(`File for competition ${competition.id} with name ${fileName} does not exist`);
		}
		// check if the file is readable
		try {
			fs.accessSync(filePath, fs.constants.R_OK);
		} catch (error) {
			throw new Error(`File for competition ${competition.id} with name ${fileName} is not readable`);
		}
		// check if columns fit configuration of the competition.
		const config = await this.evaluationConfigRepo.getById(competition.evaluation_config_id); // TODO check if mapping is required because JSON is stored as string in the database. If so, implement mapping here.
		if (!config) {
			throw new Error(`Evaluation config with ID ${competition.evaluation_config_id} not found`);
		}
		const inputNames = config.input_column_names;
		const targetNames = config.target_columns.map((tc) => tc.target_column_name);

		const fileStream = fs.createReadStream(filePath);
		const rl = readline.createInterface({
			input: fileStream,
			crlfDelay: Infinity,
		});

		let headerline = "";
		for await (const line of rl) {
			headerline = line;
			break; // only read the first line
		}
		rl.close();

		const actualColumns = headerline.split(",").map((col) => col.trim());
		const missingInputColumns = inputNames.filter((col) => !actualColumns.includes(col));
        const missingTargetColumns = targetNames.filter((col) => !actualColumns.includes(col));
        if (missingInputColumns.length > 0) {
            // delete the uploaded file to avoid orphaned files
            fs.unlinkSync(filePath);
            throw new BadRequestException(`Missing input columns in dataset: ${missingInputColumns.join(", ")}`);
        }
        if (missingTargetColumns.length > 0) {
            fs.unlinkSync(filePath);
            throw new BadRequestException(`Missing target columns in dataset: ${missingTargetColumns.join(", ")}`);
        }

		const dataset: Dataset = {
			id: 0, // Assuming the ID will be auto-generated by the database
			competitionId: competition.id,
			dataset_type: datasetType,
			file_name: fileName,
			file_path: filePath,
		};

		return await this.datasetRepo.createDataset(dataset);
	}

	/**
	 * gets the dataset for a given competition and dataset type.
	 * @param id
	 * @param datasetType
	 * @returns Dataset for the given competition and dataset type
	 * @throws Error if no dataset is found or if multiple datasets are found for the same competition and type.
	 * @throws Error if the file for the dataset does not exist on the filesystem.
	 */
	async getDatasetsForCompetition(id: number, datasetType: DatasetType): Promise<Dataset | null> {
		const dbResults = await this.datasetRepo.getDatasetsForCompetitionAndType(id, datasetType);
		if (!dbResults || dbResults.length === 0) {
			return null; // No dataset found for the given competition and type
		}
		if (dbResults.length > 1) {
			throw new Error(`Multiple datasets found for competition ID ${id} and dataset type ${datasetType}`);
		}

		const dataset = dbResults[0];
		if (!fs.existsSync(dataset.file_path)) {
			throw new Error(`File not found for dataset ID ${dataset.id}`);
		}
		return dataset;
	}

	async deleteDatasetById(id: number): Promise<Dataset | null> {
		const dataset = await this.datasetRepo.getById(id);
		if (!dataset) {
			return null; // No dataset found for the given ID
		}

		// Delete the file from the filesystem
		if (fs.existsSync(dataset.file_path)) {
			fs.unlinkSync(dataset.file_path);
		}

		// Delete the dataset from the database
		const success = await this.datasetRepo.deleteById(id);
		if (!success) {
			throw new Error(`Failed to delete dataset with ID ${id} from the database`);
		}
		return dataset;
	}
}
